#!/usr/bin/env bash
# Builds both games into Fefe bundles (see Fefe docs → "Bundling an HTML5 game"):
# index.html at the zip root, relative paths only, no CDN dependencies.
#
#   FEFE_API_URL=https://<gateway>/fefe/api \
#   ADINKRA_GAME_ID=12 ANANSE_GAME_ID=13 scripts/bundle.sh
#
# Game IDs are only a fallback for offline copies opened from disk; hosted
# copies get window.GAME_ID from Fefe.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/dist"
API="${FEFE_API_URL:-http://localhost/fefe/api}"
rm -rf "$OUT" && mkdir -p "$OUT"

config() { # <dir> <gameId> <slug>
  printf '// Generated by scripts/bundle.sh\nwindow.FEFE_CONFIG = { gameId: %s, apiUrl: "%s", slug: "%s" };\n' \
    "${2:-0}" "$API" "$3" > "$1/fefe-config.js"
  cp "$ROOT/shared/fefe.js" "$1/fefe.js"
}

check() { # <zip>
  local zip="$1"
  unzip -l "$zip" | grep -E ' index\.html$' >/dev/null || { echo "✗ $zip: no index.html at root"; exit 1; }
  if unzip -p "$zip" '*.html' '*.js' '*.css' 2>/dev/null | grep -nE '(src|href)="/[^/]'; then
    echo "✗ $zip: absolute asset paths"; exit 1
  fi
  if unzip -p "$zip" '*.html' '*.js' '*.css' 2>/dev/null | grep -nE '(src|href)="https?://'; then
    echo "✗ $zip: external (CDN) assets break offline play"; exit 1
  fi
  echo "✓ $(basename "$zip") $(du -h "$zip" | cut -f1)"
}

# 1. Adinkra Match (React + Vite)
(
  cd "$ROOT/adinkra-match"
  [ -d node_modules ] || npm install --silent
  config public "${ADINKRA_GAME_ID:-0}" adinkra-match
  npm run build --silent
  cd dist && rm -f "$OUT/adinkra-match.zip" && zip -qr -X "$OUT/adinkra-match.zip" . -x '.DS_Store'
  cp -R . "$OUT/adinkra-match"
)
check "$OUT/adinkra-match.zip"

# 2. Ananse Hop (plain HTML5 canvas)
STAGE="$OUT/ananse-hop"
mkdir -p "$STAGE"
cp "$ROOT/ananse-hop/"{index.html,style.css,game.js} "$STAGE/"
config "$STAGE" "${ANANSE_GAME_ID:-0}" ananse-hop
(cd "$STAGE" && zip -qr -X "$OUT/ananse-hop.zip" . -x '.DS_Store')
check "$OUT/ananse-hop.zip"

echo "Bundles in $OUT"
